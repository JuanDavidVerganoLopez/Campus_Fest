-- CampusFest: esquema relacional en H2 (ejecución repetible).
CREATE TABLE IF NOT EXISTS EVENTO (
    ID VARCHAR(100) PRIMARY KEY,
    NOMBRE VARCHAR(255) NOT NULL,
    FECHA TIMESTAMP NOT NULL,
    LUGAR VARCHAR(255) NOT NULL,
    AFORO INTEGER NOT NULL,
    BLOQUEADOS INTEGER NOT NULL,
    CONSTRAINT CK_EVENTO_AF CHECK (AFORO >= 0 AND BLOQUEADOS >= 0 AND AFORO >= BLOQUEADOS)
);

CREATE TABLE IF NOT EXISTS RESERVA (
    CODIGO VARCHAR(100) PRIMARY KEY,
    EVENTO_ID VARCHAR(100) NOT NULL,
    ESTUDIANTE_ID VARCHAR(150) NOT NULL,
    VENCE_EN TIMESTAMP NOT NULL,
    ESTADO VARCHAR(30) NOT NULL,
    CONSTRAINT FK_RESERVA_EVENTO FOREIGN KEY (EVENTO_ID) REFERENCES EVENTO(ID)
);

CREATE TABLE IF NOT EXISTS ASISTENCIA (
    CODIGO_RESERVA VARCHAR(100) PRIMARY KEY,
    HORA TIMESTAMP NOT NULL,
    CONSTRAINT FK_ASISTENCIA_RESERVA FOREIGN KEY (CODIGO_RESERVA) REFERENCES RESERVA(CODIGO)
);

CREATE INDEX IF NOT EXISTS IX_RESERVA_EVENTO ON RESERVA(EVENTO_ID);
